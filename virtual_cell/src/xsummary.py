"""Summary of the 2026-10-03 exploratory D1/D2/D3 runs -> results/xsummary.md (every number in the write-up comes from here).

Inputs: results/pod_x/{xmap_pairs,xmulti_pairs,xdesign_pairs}/*.json, results/pod_x/tahoe_xline.json (pod runs,
20 seeds; Tahoe 5 seeds), results/xpropa_s20_metrics.json (local; the paper's current recipe on the SAME seeds,
splits and pilots). Sanity check: the pilot-mean test MSE of xmap.py must equal that of xpropa.py seed by seed.
Radius comparisons are paired by seed: ratio of the learned map's exact split-conformal radius (fit m/2, calibrate m/2)
to the Prop. A outer ball of the pilot mean / of adapted ridge (all m pilots reused), mean over seeds with a 95 %
normal interval over seeds; "gap" is the share of the MSE gap between the pilot mean and the split-half noise energy
closed by the predictor.
usage: uv run python src/xsummary.py"""
import glob
import json
from pathlib import Path

import numpy as np

R = Path(__file__).resolve().parents[1] / "results"; P = R / "pod_x"
NM = {"ess": "K562", "rpe1": "RPE1", "hepg2": "HepG2", "jurkat": "Jurkat"}


def ci(v):
    v = np.asarray(v, float); m = v.mean(); h = 1.96 * v.std(ddof=1) / np.sqrt(len(v)); return m, m - h, m + h


def fmt(v, pct=True):
    m, lo, hi = ci(v)
    return f"{100 * m:+.1f}% [{100 * lo:+.1f}, {100 * hi:+.1f}]" if pct else f"{m:.3f}"


def main():
    pa = json.loads((R / "xpropa_s20_metrics.json").read_text())
    out = ["# Exploratory D1-D3 (2026-10-03): learned cross-line maps, designed pilots, Tahoe cross-line\n",
           "Generated by `src/xsummary.py`. Exploratory, not pre-registered. 20 seeds (CRISPRi), 5 seeds (Tahoe).\n"]
    # ---------------- single source ----------------
    out.append("## 1. Single source line (xmap.py): learned map from the measured source response\n")
    out.append("Radius ratio: exact split-conformal radius of the learned map / Prop. A outer ball (all pilots reused) of the "
               "pilot mean ('vs mean') and of adapted ridge-GO, the paper's current recipe ('vs ridge'). Mean over seeds [95% CI].\n")
    agg = {}
    for m in (50, 100, 200):
        out.append(f"\n### m = {m}\n\n| pair | gap rrr | gap pmap | gap ridge | rrr vs mean | rrr vs ridge | pmap vs ridge | cov rrr | cov propA ridge |\n|---|---|---|---|---|---|---|---|---|")
        for f in sorted(glob.glob(str(P / "xmap_pairs" / "*.json"))):
            d = json.loads(Path(f).read_text()); key = next(iter(d)); raw = d[key]["raw"]; s = d[key]["summary"]; p = pa[key]["raw"]
            assert np.allclose(raw[f"mean_mse_{m}"], p[f"propA_mean_mse_{m}"]), f"split mismatch {key} {m}"
            vm = np.array(raw[f"rrr_q_{m}"]) / np.array(p[f"propA_mean_q_{m}"]) - 1
            vr = np.array(raw[f"rrr_q_{m}"]) / np.array(p[f"propA_ridge_q_{m}"]) - 1
            vp = np.array(raw[f"pmap_q_{m}"]) / np.array(p[f"propA_ridge_q_{m}"]) - 1
            A, B = key.split("->")
            out.append(f"| {NM[A]}→{NM[B]} | {100 * s[f'rrr_gap_{m}']:.0f}% | {100 * s[f'pmap_gap_{m}']:.0f}% | {100 * s[f'ridge_gap_{m}']:.0f}% | "
                       f"{fmt(vm)} | {fmt(vr)} | {fmt(vp)} | {s[f'rrr_cov_{m}']:.3f} | {np.mean(p[f'propA_ridge_cov_{m}']):.3f} |")
            for k, v in (("gap_rrr", s[f"rrr_gap_{m}"]), ("gap_pmap", s[f"pmap_gap_{m}"]), ("gap_ridge", s[f"ridge_gap_{m}"]),
                         ("vr", vr.mean()), ("vm", vm.mean()), ("vr_sig", ci(vr)[2] < 0), ("cov", s[f"rrr_cov_{m}"])):
                agg.setdefault((m, k), []).append(v)
        g = lambda k: np.array(agg[(m, k)])  # noqa: E731
        out.append(f"\nm={m}, 12 pairs: gap closed rrr median {100 * np.median(g('gap_rrr')):.0f}% (range {100 * g('gap_rrr').min():.0f}–{100 * g('gap_rrr').max():.0f}%), "
                   f"PerturbMap-style {100 * np.median(g('gap_pmap')):.0f}%, ridge-GO {100 * np.median(g('gap_ridge')):.0f}%; "
                   f"rrr radius vs current recipe (Prop. A adapted ridge) median {100 * np.median(g('vr')):+.1f}% (range {100 * g('vr').min():+.1f} to {100 * g('vr').max():+.1f}%), "
                   f"CI below zero in {int(g('vr_sig').sum())}/12; rrr coverage {g('cov').min():.3f}–{g('cov').max():.3f}.\n")
    # compact table for the paper (Table 2)
    out.append("\n### Table 2 (paper): learned map vs current recipe, 12 pairs\n\n| m | gap closed rrr, median [range] | PerturbMap-style | ridge-GO | radius rrr vs Prop A ridge, median [range] | pairs CI<0 / CI>0 | PerturbMap-style radius vs Prop A ridge, median | rrr coverage |\n|---|---|---|---|---|---|---|---|")
    for m in (50, 100, 200):
        vr_all, vp_all, lo_all, hi_all = [], [], [], []
        for f in sorted(glob.glob(str(P / "xmap_pairs" / "*.json"))):
            d = json.loads(Path(f).read_text()); key = next(iter(d)); raw = d[key]["raw"]; p = pa[key]["raw"]
            vr = np.array(raw[f"rrr_q_{m}"]) / np.array(p[f"propA_ridge_q_{m}"]) - 1
            vp = np.array(raw[f"pmap_q_{m}"]) / np.array(p[f"propA_ridge_q_{m}"]) - 1
            c = ci(vr); vr_all.append(c[0]); lo_all.append(c[1]); hi_all.append(c[2]); vp_all.append(vp.mean())
        g = lambda k: np.array(agg[(m, k)])  # noqa: E731
        vr_all = np.array(vr_all)
        out.append(f"| {m} | {100 * np.median(g('gap_rrr')):.0f}% [{100 * g('gap_rrr').min():.0f}, {100 * g('gap_rrr').max():.0f}] | "
                   f"{100 * np.median(g('gap_pmap')):.0f}% | {100 * np.median(g('gap_ridge')):.0f}% | "
                   f"{100 * np.median(vr_all):+.1f}% [{100 * vr_all.min():+.1f}, {100 * vr_all.max():+.1f}] | "
                   f"{int((np.array(hi_all) < 0).sum())} / {int((np.array(lo_all) > 0).sum())} | {100 * np.median(vp_all):+.1f}% | "
                   f"{g('cov').min():.3f}–{g('cov').max():.3f} |")
    # ---------------- multi source ----------------
    out.append("\n## 2. Three source lines (xmulti.py)\n")
    out.append("avg_off = average of the other three lines + pilot offset, i.e. Prop. A with a different base predictor (exact); "
               "its radius below is the Prop. A outer ball (xpropa.py). Learned maps use exact split conformal. Ratios vs the Prop. A ball of the pilot mean.\n")
    for m in (25, 50, 100, 200):
        out.append(f"\n### m = {m}\n\n| target | gap synth | gap synth_rrr | avg_off (Prop A) vs mean | synth vs mean | synth_rrr vs mean | cov synth_rrr | cov avg_off |\n|---|---|---|---|---|---|---|---|")
        for f in sorted(glob.glob(str(P / "xmulti_pairs" / "*.json"))):
            d = json.loads(Path(f).read_text()); key = next(iter(d)); raw = d[key]["raw"]; s = d[key]["summary"]; p = pa[key]["raw"]
            base = np.array(p[f"propA_mmean_q_{m}"])
            va = np.array(p[f"propA_avg_q_{m}"]) / base - 1; vs = np.array(raw[f"synth_q_{m}"]) / base - 1
            vsr = np.array(raw[f"synth_rrr_q_{m}"]) / base - 1
            out.append(f"| {NM[key.split('->')[1]]} | {100 * s[f'synth_gap_{m}']:.0f}% | {100 * s[f'synth_rrr_gap_{m}']:.0f}% | {fmt(va)} | {fmt(vs)} | {fmt(vsr)} | "
                       f"{s[f'synth_rrr_cov_{m}']:.3f} | {np.mean(p[f'propA_avg_cov_{m}']):.3f} |")
    # ---------------- designs ----------------
    out.append("\n## 3. Designed fitting pilots + random calibration pilots (xdesign.py, rrr, m_cal = 50)\n")
    out.append("Test MSE relative to the random design (median over 12 pairs [range]); coverage of the exact split-conformal set.\n")
    out.append("| m_fit | kmeans | maxmin | dpp | big (largest responses) | coverage range (all designs) |\n|---|---|---|---|---|---|")
    for mf in (25, 50, 100):
        rows = {dn: [] for dn in ("kmeans", "maxmin", "dpp", "big")}; covs = []
        for f in sorted(glob.glob(str(P / "xdesign_pairs" / "*_s20.json"))):
            d = json.loads(Path(f).read_text()); s = d[next(iter(d))]["summary"]
            if f"random_rrr_mse_{mf}" not in s: continue
            for dn in rows: rows[dn].append(s[f"{dn}_rrr_mse_{mf}"] / s[f"random_rrr_mse_{mf}"] - 1)
            covs += [s[f"{dn}_rrr_cov_{mf}"] for dn in ("random", "kmeans", "maxmin", "dpp", "big")]
        out.append(f"| {mf} (n={len(rows['kmeans'])}) | " + " | ".join(
            f"{100 * np.median(v):+.1f}% [{100 * min(v):+.1f}, {100 * max(v):+.1f}]" for v in rows.values()) + f" | {min(covs):.3f}–{max(covs):.3f} |")
    # ---------------- Tahoe ----------------
    T = json.loads((P / "tahoe_xline.json").read_text())["results"]
    out.append(f"\n## 4. Tahoe-100M: predict a new line from the other 49 (tahoe_xline.py; {len({r['t'] for r in T})} target lines x 5 seeds)\n")
    keys = ["mse_other", "mse_simw5", "mse_simw20", "mse_pmean_50", "mse_otheroff_50", "mse_synth_50", "mse_pmean_100", "mse_otheroff_100", "mse_synth_100"]
    out.append("| quantity | mean | 5th pct |\n|---|---|---|")
    for k in keys + ["q_pmean_50", "q_otheroff_50", "q_synth_50", "cov_pmean_50", "cov_otheroff_50", "cov_synth_50", "q0_other", "cov0_other"]:
        v = np.array([r[k] for r in T if k in r]); out.append(f"| {k} | {v.mean():.3f} | {np.percentile(v, 5):.3f} |")
    rr = np.array([r["q_otheroff_50"] / r["q_pmean_50"] - 1 for r in T]); rs = np.array([r["q_synth_50"] / r["q_pmean_50"] - 1 for r in T])
    out.append(f"\nm=50 split radius vs pilot-mean split radius: other+offset {fmt(rr)}, synth {fmt(rs)} (over line x seed).")
    lines_cov = {}
    for r in T: lines_cov.setdefault(r["t"], []).append(r["cov0_other"])
    lc = np.array([np.mean(v) for v in lines_cov.values()])
    out.append(f"Zero-pilot borrowed calibration: mean coverage {lc.mean():.3f}; lines below 0.85: {(lc < 0.85).sum()}/{len(lc)}; lowest {lc.min():.3f}.\n")
    # ---------------- sensitivity: no noise-availability filter (xsens.py) ----------------
    S_ = json.loads((R / "xsens_s20_metrics.json").read_text())
    out.append("\n## 5. Sensitivity: no target-inspecting noise filter (xsens.py; all perturbations, 20 seeds)\n")
    out.append("| m | rrr radius vs Prop A adapted ridge, median [range] | pairs CI<0 / CI>0 | rrr coverage |\n|---|---|---|---|")
    for m in (50, 100, 200):
        v, lo, hi, cv = [], [], [], []
        for key, d in S_.items():
            r_ = np.array(d["raw"][f"rrr_q_{m}"]) / np.array(d["raw"][f"propA_ridge_q_{m}"]) - 1; c = ci(r_)
            v.append(c[0]); lo.append(c[1]); hi.append(c[2]); cv.append(d["summary"][f"rrr_cov_{m}"])
        v = np.array(v)
        out.append(f"| {m} | {100 * np.median(v):+.1f}% [{100 * v.min():+.1f}, {100 * v.max():+.1f}] | "
                   f"{int((np.array(hi) < 0).sum())} / {int((np.array(lo) > 0).sum())} | {min(cv):.3f}–{max(cv):.3f} |")
    # ---------------- designs on a common test set (xdesign.py --common-test) ----------------
    out.append("\n## 6. Designed fitting pilots, COMMON test set per seed (xdesign.py --common-test; rrr; m_cal = 50; 20 seeds)\n")
    out.append("Test MSE and split-conformal radius relative to the random design on the same 200 test perturbations; median over "
               "12 pairs [range]. 'kmeans' = k-means++ seeding; 'big' = largest centred source-PC norm.\n")
    out.append("| m_fit | kmeans MSE | kmeans radius | maxmin MSE | dpp MSE | big MSE | big radius | coverage range |\n|---|---|---|---|---|---|---|---|")
    for mf in (25, 50, 100):
        acc = {k: [] for k in ("km", "kmq", "mm", "dpp", "big", "bigq")}; covs = []
        for f in sorted(glob.glob(str(R / "xdesign_pairs" / "*_ct.json"))):
            d = json.loads(Path(f).read_text()); x = d[next(iter(d))]["summary"]
            if f"random_rrr_mse_{mf}" not in x: continue
            b, bq = x[f"random_rrr_mse_{mf}"], x[f"random_rrr_q_{mf}"]
            acc["km"].append(x[f"kmeans_rrr_mse_{mf}"] / b - 1); acc["kmq"].append(x[f"kmeans_rrr_q_{mf}"] / bq - 1)
            acc["mm"].append(x[f"maxmin_rrr_mse_{mf}"] / b - 1); acc["dpp"].append(x[f"dpp_rrr_mse_{mf}"] / b - 1)
            acc["big"].append(x[f"big_rrr_mse_{mf}"] / b - 1); acc["bigq"].append(x[f"big_rrr_q_{mf}"] / bq - 1)
            covs += [x[f"{dn}_rrr_cov_{mf}"] for dn in ("random", "kmeans", "maxmin", "dpp", "big")]
        f_ = lambda v: f"{100 * np.median(v):+.1f}% [{100 * min(v):+.1f}, {100 * max(v):+.1f}]"  # noqa: E731
        out.append(f"| {mf} (n={len(acc['km'])}) | {f_(acc['km'])} | {f_(acc['kmq'])} | {f_(acc['mm'])} | {f_(acc['dpp'])} | "
                   f"{f_(acc['big'])} | {f_(acc['bigq'])} | {min(covs):.3f}–{max(covs):.3f} |")
    (R / "xsummary.md").write_text("\n".join(out), encoding="utf-8"); print("\n".join(out))


if __name__ == "__main__":
    main()
